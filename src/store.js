import { EventEmitter } from 'node:events';
import { isDeepStrictEqual } from 'node:util';

export class HttpError extends Error {
  constructor(status, message) {
    super(message);
    this.statusCode = status;
  }
}

// Set by the server; a device can't send these (they'd override the real values in the API output).
const RESERVED = new Set(['id', 'created', 'modified', '_version', '_rev', '_boxes']);
const MAX_ID_LEN = 512;
const MAX_FIELD_NAME_LEN = 200;

/**
 * Normalise a caller payload into { id, fields }.
 * - "id" is matched case-insensitively (id, ID, Id).
 * - "created" / "modified" are generated by the server and ignored if supplied.
 * - A JSON null value removes the field from the record.
 */
export function normalizeInput(input, { maxFields = 500, skipEmpty = false } = {}) {
  if (!input || typeof input !== 'object' || Array.isArray(input)) {
    throw new HttpError(400, 'Payload must be an object with at least an "id" field');
  }
  let id;
  const fields = {};
  let count = 0;
  for (const [rawKey, value] of Object.entries(input)) {
    const key = String(rawKey).trim();
    if (!key) continue;
    if (key === '__proto__') continue; // never let a field name touch Object.prototype
    const lower = key.toLowerCase();
    if (lower === 'id') { id = value; continue; }
    if (RESERVED.has(lower)) continue;
    if (skipEmpty && (value === '' || value === undefined)) continue;
    if (key.length > MAX_FIELD_NAME_LEN) throw new HttpError(400, `Field name too long: "${key.slice(0, 40)}…"`);
    if (++count > maxFields) throw new HttpError(400, `Too many fields (max ${maxFields})`);
    fields[key] = value === undefined ? null : value;
  }
  if (id === undefined || id === null || (typeof id === 'object')) throw new HttpError(400, '"id" is required');
  id = String(id).trim();
  if (!id) throw new HttpError(400, '"id" is required');
  if (id.length > MAX_ID_LEN) throw new HttpError(400, `"id" too long (max ${MAX_ID_LEN})`);
  return { id, fields };
}

export const jsonPath = (field) => '$."' + String(field).replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';

/**
 * The same record as toRecord(), serialised straight from the stored JSON without parsing it.
 * Building the full list this way is several times faster, which matters because it runs on the
 * event loop that also accepts check-ins.
 */
export function recordJson(row) {
  const head = `{"id":${JSON.stringify(row.id)},"created":${JSON.stringify(row.created)},"modified":${JSON.stringify(row.modified)},"_version":${Number(row.version)},"_rev":${Number(row.rev)}`;
  const d = row.data;
  return d.length > 2 && d[0] === '{' ? head + ',' + d.slice(1) : head + '}';
}

export function toRecord(row) {
  const out = { id: row.id, created: row.created, modified: row.modified, _version: row.version, _rev: row.rev };
  const data = JSON.parse(row.data);
  for (const k in data) out[k] = data[k];
  return out;
}

/**
 * All writes go through an in-memory queue that is flushed in a single SQLite
 * transaction per event-loop tick ("group commit"). This lets thousands of
 * concurrent check-ins share one fsync instead of paying one each.
 */
export class Store extends EventEmitter {
  constructor(db, { historyLimit = 100, maxBatch = 5000, maxFields = 500 } = {}) {
    super();
    this.db = db;
    this.historyLimit = historyLimit;
    this.maxBatch = maxBatch;
    this.maxFields = maxFields;
    this.queue = [];
    this.scheduled = false;
    // The rev counter must never go backwards, even when the newest records were deleted before a
    // restart: dashboards catch up with "everything after rev N" and would miss reused numbers.
    this.rev = Math.max(
      db.prepare('SELECT COALESCE(MAX(rev), 0) AS r FROM records').get().r,
      db.prepare("SELECT COALESCE(MAX(value), 0) AS r FROM store_meta WHERE key = 'rev'").get().r,
    );
    this.saveRev = db.prepare("INSERT INTO store_meta (key, value) VALUES ('rev', ?) ON CONFLICT(key) DO UPDATE SET value = MAX(value, excluded.value)");
    this.stats = { writes: 0, batches: 0, startedAt: new Date().toISOString() };

    this.s = {
      get: db.prepare('SELECT id, data, created, modified, version, rev FROM records WHERE id = ?'),
      insert: db.prepare('INSERT INTO records (id, data, created, modified, version, rev) VALUES (?, ?, ?, ?, 1, ?)'),
      update: db.prepare('UPDATE records SET data = ?, modified = ?, version = ?, rev = ? WHERE id = ?'),
      hist: db.prepare('INSERT INTO history (record_id, version, action, changes, data, at) VALUES (?, ?, ?, ?, ?, ?)'),
      prune: db.prepare(`DELETE FROM history WHERE record_id = ? AND hid < (
        SELECT hid FROM history WHERE record_id = ? ORDER BY hid DESC LIMIT 1 OFFSET ?)`),
      pruneAll: db.prepare('DELETE FROM history WHERE record_id = ?'),
      del: db.prepare('DELETE FROM records WHERE id = ?'),
      count: db.prepare('SELECT COUNT(*) AS n FROM records'),
      histCount: db.prepare('SELECT COUNT(*) AS n FROM history'),
    };

    this.fieldCounts = new Map();
    this.#rebuildFields();
    this.#applyHistoryLimitToExisting();

    this.txn = db.transaction((ops) => this.#applyBatch(ops));
  }

  #rebuildFields() {
    this.fieldCounts.clear();
    const rows = this.db.prepare(
      'SELECT j.key AS k, COUNT(*) AS n FROM records r, json_each(r.data) j GROUP BY j.key'
    ).all();
    for (const { k, n } of rows) this.fieldCounts.set(k, n);
  }

  #bumpField(k, d) {
    const n = (this.fieldCounts.get(k) || 0) + d;
    if (n <= 0) this.fieldCounts.delete(k); else this.fieldCounts.set(k, n);
  }

  // If HISTORY_LIMIT was lowered between restarts, trim once at startup.
  #applyHistoryLimitToExisting() {
    if (this.historyLimit < 0) return;
    if (this.historyLimit === 0) { this.db.exec('DELETE FROM history'); return; }
    this.db.prepare(`DELETE FROM history WHERE hid IN (
      SELECT hid FROM (SELECT hid, ROW_NUMBER() OVER (PARTITION BY record_id ORDER BY hid DESC) AS rn FROM history)
      WHERE rn > ?)`).run(this.historyLimit);
  }

  /** Queue one upsert; resolves with { action, record, changed } once committed. */
  upsert(input, opts) {
    const { id, fields } = normalizeInput(input, { maxFields: this.maxFields, ...opts });
    return this.enqueue(id, fields);
  }

  enqueue(id, fields) {
    return new Promise((resolve, reject) => {
      this.queue.push({ id, fields, resolve, reject });
      if (!this.scheduled) {
        this.scheduled = true;
        setImmediate(() => this.flush());
      }
    });
  }

  flush() {
    this.scheduled = false;
    const ids = [];
    while (this.queue.length) {
      const batch = this.queue.splice(0, this.maxBatch);
      let results;
      try {
        results = this.txn(batch);
      } catch (err) {
        for (const op of batch) op.reject(err);
        continue;
      }
      this.stats.writes += batch.length;
      this.stats.batches++;
      // Listeners (status boxes) update before anyone can read the new rev.
      try { this.emit('written', results); } catch (err) { console.error('written listener failed:', err); }
      for (let i = 0; i < batch.length; i++) {
        batch[i].resolve(results[i]);
        ids.push(batch[i].id);
      }
    }
    if (ids.length) this.emit('change', { rev: this.rev, count: ids.length });
  }

  #applyBatch(ops) {
    const results = new Array(ops.length);
    const touched = new Set();
    const keepHistory = this.historyLimit !== 0;
    for (let i = 0; i < ops.length; i++) {
      const { id, fields } = ops[i];
      const now = new Date().toISOString();
      const row = this.s.get.get(id);
      const rev = ++this.rev;
      if (!row) {
        const data = {};
        const changes = {};
        for (const k in fields) {
          if (fields[k] === null) continue;
          data[k] = fields[k];
          changes[k] = [null, fields[k]];
          this.#bumpField(k, 1);
        }
        const json = JSON.stringify(data);
        this.s.insert.run(id, json, now, now, rev);
        if (keepHistory) this.s.hist.run(id, 1, 'create', JSON.stringify(changes), json, now);
        results[i] = { action: 'created', changed: Object.keys(changes),
          record: { id, created: now, modified: now, _version: 1, _rev: rev, ...data } };
      } else {
        const data = JSON.parse(row.data);
        const changes = {};
        for (const k in fields) {
          const v = fields[k];
          const had = Object.prototype.hasOwnProperty.call(data, k);
          if (v === null) {
            if (had) { changes[k] = [data[k], null]; delete data[k]; this.#bumpField(k, -1); }
          } else if (!had || !isDeepStrictEqual(data[k], v)) {
            changes[k] = [had ? data[k] : null, v];
            if (!had) this.#bumpField(k, 1);
            data[k] = v;
          }
        }
        const version = row.version + 1;
        const json = JSON.stringify(data);
        this.s.update.run(json, now, version, rev, id);
        // Every check-in is an event, so it is logged even when no field values changed.
        if (keepHistory) this.s.hist.run(id, version, 'update', JSON.stringify(changes), json, now);
        results[i] = { action: 'updated', changed: Object.keys(changes),
          record: { id, created: row.created, modified: now, _version: version, _rev: rev, ...data } };
      }
      touched.add(id);
    }
    if (this.historyLimit > 0) {
      for (const id of touched) this.s.prune.run(id, id, this.historyLimit - 1);
    }
    return results;
  }

  get(id) {
    const row = this.s.get.get(id);
    if (!row) return null;
    const rec = toRecord(row);
    const extra = this.decorate && this.decorate(id);
    if (extra) rec._boxes = { ...extra };
    return rec;
  }

  /**
   * Query records.
   * filters: { field: value } exact match (string compare); q: free-text over id + data.
   */
  list(opts = {}) {
    const { rows, total } = this.#query(opts);
    return { records: rows.map(toRecord), total, rev: this.rev };
  }

  /** list() as a JSON string (what the API sends). */
  listJson(opts = {}) {
    const { rows, total } = this.#query(opts);
    let out = '{"records":[';
    const deco = this.decorate;
    for (let i = 0; i < rows.length; i++) {
      let j = recordJson(rows[i]);
      const extra = deco && deco(rows[i].id);
      if (extra) j = j.slice(0, -1) + ',"_boxes":' + JSON.stringify(extra) + '}';
      out += (i ? ',' : '') + j;
    }
    return out + `],"total":${total},"rev":${this.rev}}`;
  }

  #query({ sinceRev, q, filters = {}, match = 'all', ranges = [], sort, order, limit, offset } = {}) {
    const where = [];
    const params = [];
    if (sinceRev !== undefined && sinceRev !== null && sinceRev !== '') {
      where.push('rev > ?');
      params.push(Number(sinceRev) || 0);
    }
    if (q) {
      const like = `%${String(q).replace(/[%_\\]/g, (m) => '\\' + m)}%`;
      where.push("(id LIKE ? ESCAPE '\\' OR data LIKE ? ESCAPE '\\')");
      params.push(like, like);
    }
    // Field filters combine with AND (match=all, default) or OR (match=any).
    const fw = [];
    for (const [field, value] of Object.entries(filters)) {
      if (field.toLowerCase() === 'id') { fw.push('id = ?'); params.push(String(value)); continue; }
      if (field === 'created' || field === 'modified') { fw.push(`${field} >= ?`); params.push(String(value)); continue; }
      fw.push('CAST(json_extract(data, ?) AS TEXT) = ?');
      params.push(jsonPath(field), String(value));
    }
    if (fw.length) where.push('(' + fw.join(String(match).toLowerCase() === 'any' ? ' OR ' : ' AND ') + ')');
    // Time ranges / status: always ANDed. Each entry is a group of OR'd
    // conditions: [[{ field, op: '>=' | '<', value }...], ...].
    for (const group of ranges) {
      const parts = [];
      for (const conds of group) {
        const and = [];
        for (const { field, op, value } of conds) {
          if (!['created', 'modified'].includes(field) || !['>=', '<'].includes(op)) continue;
          and.push(`${field} ${op} ?`);
          params.push(String(value));
        }
        if (and.length) parts.push('(' + and.join(' AND ') + ')');
      }
      if (parts.length) where.push('(' + parts.join(' OR ') + ')');
    }
    let sql = 'SELECT id, data, created, modified, version, rev FROM records';
    let countSql = 'SELECT COUNT(*) AS n FROM records';
    if (where.length) {
      sql += ' WHERE ' + where.join(' AND ');
      countSql += ' WHERE ' + where.join(' AND ');
    }
    const dir = String(order).toLowerCase() === 'desc' ? 'DESC' : 'ASC';
    const sortParams = [];
    if (!sort || sort === 'rev') sql += ` ORDER BY rev ${dir}`;
    else if (['id', 'created', 'modified'].includes(sort)) sql += ` ORDER BY ${sort} ${dir}`;
    else { sql += ` ORDER BY json_extract(data, ?) ${dir}, id`; sortParams.push(jsonPath(sort)); }
    const pageParams = [];
    if (limit !== undefined && limit !== null && limit !== '') {
      sql += ' LIMIT ? OFFSET ?';
      pageParams.push(Math.max(0, Number(limit) || 0), Math.max(0, Number(offset) || 0));
    }
    const rows = this.db.prepare(sql).all(...params, ...sortParams, ...pageParams);
    const total = this.db.prepare(countSql).get(...params).n;
    return { rows, total };
  }

  /** Iterate every record (for CSV export) without loading them all at once. */
  *iterate() {
    for (const row of this.db.prepare('SELECT id, data, created, modified, version, rev FROM records ORDER BY id').iterate()) {
      yield toRecord(row);
    }
  }

  history(id, { limit = 500 } = {}) {
    return this.db.prepare(
      'SELECT hid, record_id AS id, version, action, changes, data, at FROM history WHERE record_id = ? ORDER BY hid DESC LIMIT ?'
    ).all(id, Math.min(Number(limit) || 500, 100000)).map(parseHist);
  }

  /**
   * Newest history across all records. `before` pages back (hid < before); `after` returns
   * only entries newer than a hid the caller already has. `data: false` leaves out the full
   * snapshot of each entry (the activity feed only needs the changes).
   */
  recentHistory({ limit = 200, before, after, data = true } = {}) {
    const lim = Math.min(Number(limit) || 200, 5000);
    const cols = data ? 'hid, record_id AS id, version, action, changes, data, at' : 'hid, record_id AS id, version, action, changes, at';
    let rows;
    if (before) rows = this.db.prepare(`SELECT ${cols} FROM history WHERE hid < ? ORDER BY hid DESC LIMIT ?`).all(Number(before), lim);
    else if (after !== undefined && after !== null && after !== '') rows = this.db.prepare(`SELECT ${cols} FROM history WHERE hid > ? ORDER BY hid DESC LIMIT ?`).all(Number(after) || 0, lim);
    else rows = this.db.prepare(`SELECT ${cols} FROM history ORDER BY hid DESC LIMIT ?`).all(lim);
    return rows.map(parseHist);
  }

  /** Every record id plus the current rev (lets a reconnecting dashboard drop deleted records). */
  ids() {
    return { ids: this.db.prepare('SELECT id FROM records').all().map((r) => r.id), rev: this.rev };
  }

  *iterateHistory() {
    for (const row of this.db.prepare('SELECT hid, record_id AS id, version, action, changes, data, at FROM history ORDER BY record_id, hid').iterate()) {
      yield parseHist(row);
    }
  }

  delete(id) {
    const row = this.s.get.get(id);
    if (!row) return false;
    this.db.transaction(() => {
      this.s.del.run(id);
      this.s.pruneAll.run(id);
      this.saveRev.run(this.rev);
    })();
    for (const k in JSON.parse(row.data)) this.#bumpField(k, -1);
    this.emit('delete', { ids: [id] });
    return true;
  }

  /** Delete many records (and their history) in one transaction. Returns the ids that existed. */
  deleteMany(ids) {
    const unique = [...new Set(ids.map(String))];
    const deleted = [];
    this.db.transaction(() => {
      for (const id of unique) {
        const row = this.s.get.get(id);
        if (!row) continue;
        this.s.del.run(id);
        this.s.pruneAll.run(id);
        for (const k in JSON.parse(row.data)) this.#bumpField(k, -1);
        deleted.push(id);
      }
      if (deleted.length) this.saveRev.run(this.rev);
    })();
    if (deleted.length) this.emit('delete', { ids: deleted });
    return deleted;
  }

  /** Remove every record and every history entry. */
  clearAll() {
    this.flush(); // commit anything already queued first so it is cleared too
    const records = this.s.count.get().n;
    const history = this.s.histCount.get().n;
    this.db.transaction(() => {
      this.db.exec('DELETE FROM records; DELETE FROM history;');
      this.saveRev.run(this.rev);
    })();
    this.db.pragma('wal_checkpoint(TRUNCATE)');
    this.fieldCounts.clear();
    this.emit('clear', {});
    return { records, history };
  }

  fields() {
    return [...this.fieldCounts.entries()]
      .map(([name, count]) => ({ name, count }))
      .sort((a, b) => b.count - a.count || a.name.localeCompare(b.name));
  }

  summary() {
    return {
      records: this.s.count.get().n,
      history: this.s.histCount.get().n,
      fields: this.fieldCounts.size,
      rev: this.rev,
      historyLimit: this.historyLimit,
      queue: this.queue.length,
      ...this.stats,
    };
  }
}

function parseHist(r) {
  return { hid: r.hid, id: r.id, version: r.version, action: r.action, at: r.at,
    changes: JSON.parse(r.changes), ...(r.data !== undefined ? { data: JSON.parse(r.data) } : {}) };
}
