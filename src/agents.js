import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from './config.js';

/*
 * Agent downloads and one-line installers (all public: nothing here is secret).
 *
 *   GET /agent/checkin-agent.sh    the Linux agent   (scripts/checkin-agent.sh)
 *   GET /agent/checkin-agent.ps1   the Windows agent (scripts/checkin-agent.ps1)
 *   GET /install.sh                Linux installer:   curl -fsSL https://SITE/install.sh | sudo bash
 *   GET /install.ps1               Windows installer: irm https://SITE/install.ps1 | iex
 *
 * The installers download the agent from this site and set it up to report back here.
 * Options can be given on the install URL and become the installed defaults:
 *   ?every=10                     minutes between check-ins (Linux 1-59, Windows 1-1439; default 5)
 *   &fields=default,security      field groups (see the agent scripts)
 *   &exclude=users                field groups to leave out
 *   &extra=site=Dallas,owner=it   extra fields; values may use the machine's environment variables,
 *                                 read on every run: site=${SITE}, owner=${OWNER:-it} or site=%SITE%
 *   &insecure=1                   accept a self-signed certificate
 *   &url=https://checkin.example.com   override the server address baked into the installer
 *
 * WHERE TO CHANGE THINGS
 *   - Defaults for every new install: INSTALL_DEFAULTS below (or pass the URL options above).
 *   - What the agents collect and how: scripts/checkin-agent.sh and scripts/checkin-agent.ps1
 *     (each has a "SETTINGS - change these" block near the top).
 *   - One machine after installing: /etc/check-in/agent.conf (Linux) or
 *     C:\ProgramData\CheckIn\agent.json (Windows). Changes apply on the next run.
 */
export const INSTALL_DEFAULTS = {
  every: 5,
  fields: 'default',
  exclude: '',
  extra: '',
};

export const AGENT_GROUPS = ['system', 'cpu', 'ram', 'disk', 'time', 'uptime', 'network', 'domain', 'users', 'health', 'updates', 'security'];
export const DEFAULT_GROUPS = ['system', 'cpu', 'ram', 'disk', 'time', 'uptime', 'network', 'domain', 'users', 'health'];

const AGENTS = {
  'checkin-agent.sh': 'text/x-shellscript; charset=utf-8',
  'checkin-agent.ps1': 'text/plain; charset=utf-8',
};

class BadOption extends Error { constructor(m) { super(m); this.statusCode = 400; } }

/** The address machines should use to reach this server. */
export function siteUrl(req, override) {
  if (override) {
    let u;
    try { u = new URL(String(override)); } catch { throw new BadOption('url must be a full address like https://checkin.example.com'); }
    if (!/^https?:$/.test(u.protocol)) throw new BadOption('url must start with http:// or https://');
    return u.origin;
  }
  const host = String(req.host || req.headers.host || '');
  if (!/^[A-Za-z0-9.\-[\]:]{1,255}$/.test(host)) throw new BadOption('Could not work out this server\'s address; add ?url=https://your-server');
  return `${req.protocol}://${host}`;
}

/** Validate install options. Values end up inside generated scripts, so only safe characters are allowed. */
export function installOptions(q, { maxEvery }) {
  const opt = { ...INSTALL_DEFAULTS };
  if (q.every !== undefined && q.every !== '') {
    const n = Number(q.every);
    if (!Number.isInteger(n) || n < 1 || n > maxEvery) throw new BadOption(`every must be a whole number of minutes from 1 to ${maxEvery}`);
    opt.every = n;
  }
  for (const k of ['fields', 'exclude']) {
    if (q[k] === undefined) continue;
    const v = String(q[k]).toLowerCase().replace(/\s+/g, '');
    for (const g of v.split(',').filter(Boolean)) {
      if (g !== 'all' && g !== 'default' && !AGENT_GROUPS.includes(g)) throw new BadOption(`unknown field group in ${k}: ${g}`);
    }
    opt[k] = v.split(',').filter(Boolean).join(',');
  }
  if (!opt.fields) opt.fields = 'default';
  if (q.extra !== undefined) {
    const v = String(q.extra).trim();
    // $ { } % are allowed for environment variable references; the installers store them literally.
    if (v.length > 300 || !/^[A-Za-z0-9_.:@/ =,+${}%-]*$/.test(v)) throw new BadOption('extra may only use letters, numbers, spaces, environment variables like ${NAME} or %NAME%, and _ . : @ / = , + -');
    if (/\$(?!\{[A-Za-z_][A-Za-z0-9_]*(:-[^}$]*)?\})/.test(v)) throw new BadOption('in extra, $ may only be used as ${NAME} or ${NAME:-fallback}');
    opt.extra = v;
  }
  opt.insecure = q.insecure === '1' || q.insecure === 'true';
  return opt;
}

function linuxInstaller(site, o) {
  return `#!/usr/bin/env bash
# Check-In agent installer for Linux, generated by ${site} on ${new Date().toISOString()}
#
#   curl -fsSL ${site}/install.sh | sudo bash
#   curl -fsSL ${site}/install.sh | sudo CHECKIN_API_KEY=ck_xxx bash     (when the server has an API key)
#
# Downloads the agent from this server, installs it to /usr/local/bin/checkin-agent, saves its
# settings to /etc/check-in/agent.conf (root only) and runs it every few minutes (systemd timer,
# or cron when there is no systemd; set CHECKIN_CRON=1 to always use cron).
# Afterwards: sudo checkin-agent --dry-run    sudo checkin-agent --uninstall
#
# ---- SETTINGS - change these here, with ?every=10&fields=... on the install URL, ----------------
# ---- or with CHECKIN_* environment variables (e.g. sudo CHECKIN_EVERY=10 bash) ------------------
SERVER="\${CHECKIN_URL:-${site}}"
EVERY="\${CHECKIN_EVERY:-${o.every}}"                # minutes between check-ins (1-59)
FIELDS="\${CHECKIN_FIELDS:-${o.fields}}"             # field groups: default, all, or e.g. cpu,ram,disk
EXCLUDE="\${CHECKIN_EXCLUDE:-${o.exclude}}"          # field groups to leave out
EXTRA="\${CHECKIN_EXTRA:-}"                         # extra fields, e.g. 'site=Dallas,owner=\${OWNER:-it}'
[ -n "$EXTRA" ] || EXTRA='${o.extra}'   # single quotes: \${NAME} and %NAME% are read on each run, not now
INSECURE="\${CHECKIN_INSECURE:-${o.insecure ? 1 : ''}}"           # 1 = accept a self-signed certificate
# --------------------------------------------------------------------------------------------------
set -eu
if [ "$(id -u)" != 0 ]; then echo "Please run as root:  curl -fsSL $SERVER/install.sh | sudo bash" >&2; exit 1; fi
command -v curl >/dev/null 2>&1 || { echo "curl is required" >&2; exit 1; }
K=""; [ "$INSECURE" = 1 ] && K="-k"
TMP=$(mktemp); trap 'rm -f "$TMP"' EXIT
echo "Downloading the Check-In agent from $SERVER ..."
curl -fsS $K "$SERVER/agent/checkin-agent.sh" -o "$TMP"
set -- --install --url "$SERVER" --every "$EVERY" --fields "$FIELDS"
[ -n "$EXCLUDE" ] && set -- "$@" --exclude "$EXCLUDE"
[ -n "$EXTRA" ] && set -- "$@" --extra "$EXTRA"
[ "$INSECURE" = 1 ] && set -- "$@" --insecure
[ "\${CHECKIN_CRON:-}" = 1 ] && set -- "$@" --cron
bash "$TMP" "$@" </dev/null
`;
}

function windowsInstaller(site, o) {
  const q = (s) => String(s).replace(/'/g, "''");
  return `# Check-In agent installer for Windows, generated by ${site} on ${new Date().toISOString()}
#
# In an elevated PowerShell (Run as administrator):
#   irm ${site}/install.ps1 | iex
#   $env:CHECKIN_API_KEY='ck_xxx'; irm ${site}/install.ps1 | iex     (when the server has an API key)
#
# Downloads the agent from this server to C:\\ProgramData\\CheckIn, saves its settings there
# (agent.json, readable by administrators and SYSTEM only) and creates the scheduled task
# "Check-In Agent", which runs as SYSTEM every few minutes, at startup and on battery.
# Afterwards: last result in C:\\ProgramData\\CheckIn\\last-run.txt
#             remove with: powershell -ExecutionPolicy Bypass -File C:\\ProgramData\\CheckIn\\checkin-agent.ps1 -Uninstall
& {
  # ---- SETTINGS - change these here, with ?every=10&fields=... on the install URL, --------------
  # ---- or with $env:CHECKIN_* variables set before running (e.g. $env:CHECKIN_EVERY='10') -------
  $Server   = if ($env:CHECKIN_URL)     { $env:CHECKIN_URL }     else { '${q(site)}' }
  $Every    = if ($env:CHECKIN_EVERY)   { $env:CHECKIN_EVERY }   else { '${o.every}' }       # minutes (1-1439)
  $Fields   = if ($env:CHECKIN_FIELDS)  { $env:CHECKIN_FIELDS }  else { '${q(o.fields)}' }   # default, all, or e.g. cpu,ram,disk
  $Exclude  = if ($env:CHECKIN_EXCLUDE) { $env:CHECKIN_EXCLUDE } else { '${q(o.exclude)}' }  # groups to leave out
  $Extra    = if ($env:CHECKIN_EXTRA)   { $env:CHECKIN_EXTRA }   else { '${q(o.extra)}' }    # e.g. site=%SITE%,owner=it (%NAME% / \${NAME} are read on each run)
  $Insecure = ${o.insecure ? '$true' : '$false'}                                             # $true = accept a self-signed certificate
  # -----------------------------------------------------------------------------------------------
  $ErrorActionPreference = 'Stop'
  $ProgressPreference = 'SilentlyContinue'
  $id = [Security.Principal.WindowsIdentity]::GetCurrent()
  if (-not (New-Object Security.Principal.WindowsPrincipal($id)).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
    Write-Warning 'Please run this in an elevated PowerShell (Run as administrator).'; return
  }
  [Net.ServicePointManager]::SecurityProtocol = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12
  $dl = @{ UseBasicParsing = $true; Uri = "$Server/agent/checkin-agent.ps1"; OutFile = (Join-Path $env:TEMP 'checkin-agent.ps1') }
  if ($Insecure) {
    if ($PSVersionTable.PSVersion.Major -ge 6) { $dl.SkipCertificateCheck = $true }
    else { [Net.ServicePointManager]::ServerCertificateValidationCallback = { $true } }
  }
  Write-Host "Downloading the Check-In agent from $Server ..."
  Invoke-WebRequest @dl
  $a = @('-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', $dl.OutFile, '-Install', '-Url', $Server, '-Every', $Every, '-Fields', $Fields)
  if ($Exclude) { $a += @('-Exclude', $Exclude) }
  if ($Extra) { $a += @('-Extra', $Extra) }
  if ($Insecure) { $a += '-Insecure' }
  # Runs in a separate Windows PowerShell so the agent's exit codes can't close this window.
  & (Join-Path $env:SystemRoot 'System32\\WindowsPowerShell\\v1.0\\powershell.exe') @a
  if ($LASTEXITCODE -ne 0) { Write-Warning "The installer reported a problem (exit code $LASTEXITCODE)." }
  Remove-Item -LiteralPath $dl.OutFile -Force -ErrorAction SilentlyContinue
}
`;
}

export function registerAgentRoutes(app) {
  const pub = { config: { cap: 'public' } };
  const text = (reply, type, body) => reply.type(type).header('cache-control', 'no-store').send(body);

  app.get('/agent/:file', pub, async (req, reply) => {
    const type = AGENTS[req.params.file];
    if (!type) return reply.code(404).send({ ok: false, error: 'Not found' });
    return text(reply, type, await fs.promises.readFile(path.join(ROOT, 'scripts', req.params.file)));
  });

  const installer = (build, maxEvery, type) => async (req, reply) => {
    try {
      const site = siteUrl(req, req.query.url);
      return text(reply, type, build(site, installOptions(req.query, { maxEvery })));
    } catch (e) {
      if (!(e instanceof BadOption)) throw e;
      // Plain text that fails loudly whichever shell it is piped into.
      const msg = `Check-In installer: ${e.message}`;
      return reply.code(400).type('text/plain; charset=utf-8').send(type.includes('shell') ? `echo '${msg.replace(/'/g, '')}' >&2; exit 1\n` : `throw '${msg.replace(/'/g, "''")}'\n`);
    }
  };
  app.get('/install.sh', pub, installer(linuxInstaller, 59, 'text/x-shellscript; charset=utf-8'));
  app.get('/install.ps1', pub, installer(windowsInstaller, 1439, 'text/plain; charset=utf-8'));
}
